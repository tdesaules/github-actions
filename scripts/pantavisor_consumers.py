#!/usr/bin/env python3
"""Render six-job consumers; activate only a real, published catalogue release."""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
HEADER = '# Generated by github-actions/scripts/pantavisor_consumers.py\n'
PIN = re.compile(r'^ghcr\.io/[a-z0-9._/-]+@sha256:[a-f0-9]{64}$')


def step(text, name, replacement):
    pattern = re.compile(r'^      - name: ' + re.escape(name) + r'\n.*?(?=^      - |\Z)', re.M | re.S)
    result, count = pattern.subn(lambda _: replacement, text)
    if count != 1:
        raise ValueError(f'Expected one step named {name!r}, got {count}')
    return result


def system(template):
    prefix, rest = template.split('  build:\n', 1)
    build, rest = ('  build:\n' + rest).split('  test:\n', 1)
    test, rest = ('  test:\n' + rest).split('  release:\n', 1)
    release, maintenance = ('  release:\n' + rest).split('  maintenance:\n', 1)
    maintenance = '  maintenance:\n' + maintenance
    prefix = prefix.replace('uses: tdesaules/github-actions/check/test-python@__CATALOG_TAG__\n        with:\n          tests-directory: tests',
                            'uses: tdesaules/github-actions/check/test-pantavisor-system@__CATALOG_TAG__')
    prefix = prefix.replace('      actionlint:', '      core: ${{ steps.components.outputs.core }}\n      k0s: ${{ steps.components.outputs.k0s }}\n      actionlint:', 1)
    prefix = prefix.replace('      - name: Retain exact candidate commit', '''      - name: Read immutable component inputs
        id: components
        uses: tdesaules/github-actions/workflow/read-pantavisor-components@__CATALOG_TAG__
      - name: Retain exact candidate commit''', 1)
    build = build.replace('    timeout-minutes: 330', '    timeout-minutes: 330\n    permissions: {contents: read, packages: read}')
    build = build.replace('/workflow/package-pantavisor-component@', '/workflow/package-pantavisor-bsp@')
    build = build.replace('with: {directory: dist/component}', 'with: {directory: dist/bsp}')
    components = ''
    for name in ('core', 'k0s'):
        components += f'''      - name: Fetch {name} by digest
        uses: tdesaules/github-actions/oci/get-component@__CATALOG_TAG__
        with:
          reference: ${{{{ needs.check.outputs.{name} }}}}
          output: dist/{name}
          registry-username: ${{{{ github.actor }}}}
          registry-password: ${{{{ github.token }}}}
      - name: Read verified {name} identity
        id: {name}
        uses: tdesaules/github-actions/oci/test-component@__CATALOG_TAG__
        with: {{directory: dist/{name}}}
      - name: Verify {name} publisher signature
        continue-on-error: true
        uses: tdesaules/github-actions/oci/test-image-signature@__CATALOG_TAG__
        with:
          image: ${{{{ needs.check.outputs.{name} }}}}
          identity: https://github.com/${{{{ github.repository_owner }}}}/pantavisor-{name}/.github/workflows/main.yml@refs/tags/v${{{{ steps.{name}.outputs.version }}}}
          issuer: https://token.actions.githubusercontent.com
          output: artifacts/inputs/{name}-signature.json
          registry-username: ${{{{ github.actor }}}}
          registry-password: ${{{{ github.token }}}}
'''
    components += '''      - name: Assemble base
        uses: tdesaules/github-actions/workflow/assemble-pantavisor@__CATALOG_TAG__
        with: {profile: base, output: dist/platform-base}
      - name: Assemble k0s
        uses: tdesaules/github-actions/workflow/assemble-pantavisor@__CATALOG_TAG__
        with: {profile: k0s, k0s: dist/k0s, output: dist/platform-k0s}
'''
    build = step(build, 'Assemble ARM64 OCI archive without execution', components)
    test = test.replace('    timeout-minutes: 60', '''    timeout-minutes: 150
    strategy:
      fail-fast: false
      matrix:
        profile: [base, k0s]''')
    test = test.replace('    outputs:\n      artifact-id: ${{ steps.qualified-upload.outputs.artifact-id }}\n', '')
    test = step(test, 'Test rootfs executables', '''      - name: Qualify complete platform
        uses: tdesaules/github-actions/workflow/test-pantavisor-platform@__CATALOG_TAG__
        with:
          bundle: dist/platform-${{ matrix.profile }}
          output: artifacts/qualification-${{ matrix.profile }}
          reports: artifacts/reports
''')
    test = test.replace('source: oci-archive:dist/image.oci.tar', 'source: dir:dist/bsp')
    test = test.replace('      - name: Record successful qualification\n', '      - name: Record successful qualification\n')
    test = step(test, 'Record successful qualification', '''      - name: Record successful qualification
        uses: tdesaules/github-actions/workflow/new-pantavisor-qualification@__CATALOG_TAG__
        with:
          revision: ${{ needs.check.outputs.revision }}
          profile: ${{ matrix.profile }}
''')
    test = step(test, 'Transfer exact qualified outputs', '''      - name: Retain tested platform outputs
        if: matrix.profile == 'base'
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: tested-system-base-${{ needs.build.outputs.artifact-id }}-${{ github.run_attempt }}
          path: |
            dist/
            artifacts/qualified-receipt.json
          compression-level: 0
          if-no-files-found: error
      - name: Retain independent k0s qualification
        if: matrix.profile == 'k0s'
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: tested-system-k0s-${{ needs.build.outputs.artifact-id }}-${{ github.run_attempt }}
          path: artifacts/qualified-receipt.json
          if-no-files-found: error
''')
    test = test.replace('name: test-reports-${{ env.PROJECT }}', 'name: test-reports-system-${{ matrix.profile }}')
    release = step(release, 'Fetch current qualification', '''      - name: Find matching profile artifacts across attempts
        id: profiles
        if: github.event_name == 'workflow_dispatch'
        uses: tdesaules/github-actions/workflow/get-pantavisor-qualification@__CATALOG_TAG__
        with:
          build-artifact-id: ${{ needs.build.outputs.artifact-id }}
          token: ${{ github.token }}
      - name: Fetch base qualification
        if: github.event_name == 'workflow_dispatch'
        uses: actions/download-artifact@9000827ccba6bdab643e8b6fd33ac0654aef8333
        with: {artifact-ids: '${{ steps.profiles.outputs.base-id }}', path: ., merge-multiple: true}
      - name: Fetch k0s qualification
        if: github.event_name == 'workflow_dispatch'
        uses: actions/download-artifact@9000827ccba6bdab643e8b6fd33ac0654aef8333
        with: {artifact-ids: '${{ steps.profiles.outputs.k0s-id }}', path: artifacts/profile-k0s, merge-multiple: true}
      - name: Require both profiles against identical artifacts
        if: github.event_name == 'workflow_dispatch'
        uses: tdesaules/github-actions/workflow/merge-pantavisor-qualification@__CATALOG_TAG__
        with: {revision: '${{ needs.check.outputs.revision }}'}
      - name: Retain complete platform qualification
        id: complete-upload
        if: github.event_name == 'workflow_dispatch'
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: qualified-system-${{ github.run_attempt }}
          path: |
            dist/
            artifacts/qualified-receipt.json
          compression-level: 0
          retention-days: 30
          if-no-files-found: error
''')
    release = release.replace('${{ needs.test.outputs.artifact-id }}', '${{ steps.complete-upload.outputs.artifact-id }}')
    for name in ('Publish exact OCI archive by digest', 'Sign image', 'Verify image signature'):
        release = step(release, name, '')
    release = release.replace('directory: dist/component', 'directory: dist/bsp')
    release = release.replace('registry: ghcr.io/${{ github.repository }}/component', 'registry: ghcr.io/${{ github.repository }}/bsp')
    release = release.replace('          image: ghcr.io/${{ github.repository }}@${{ steps.qualified.outputs.image-digest }}\n', '')
    maintenance = step(maintenance, 'Generate published image SBOM', '''      - name: Fetch published BSP
        if: ${{ !cancelled() && steps.published.outputs.has-release == 'true' }}
        uses: tdesaules/github-actions/oci/get-component@__CATALOG_TAG__
        with:
          reference: ${{ steps.published.outputs.component }}
          output: artifacts/maintenance/bsp
          registry-username: ${{ github.actor }}
          registry-password: ${{ github.token }}
      - name: Inventory published BSP
        continue-on-error: true
        if: ${{ !cancelled() && steps.published.outputs.has-release == 'true' }}
        uses: tdesaules/github-actions/oci/new-sbom@__CATALOG_TAG__
        with:
          source: dir:artifacts/maintenance/bsp
          format: syft-json
          output: artifacts/maintenance/sbom.syft.json
''')
    return prefix + build + test + release + maintenance


def render(project, tag):
    if project not in ('core', 'k0s', 'system'):
        raise ValueError('Unknown Pantavisor project')
    if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', tag):
        raise ValueError('Catalogue tag must be stable SemVer without v')
    text = (ROOT / 'templates/pantavisor-producer.yml').read_text()
    if project == 'system':
        text = system(text)
    return HEADER + text.replace('__PROJECT__', project).replace('__CATALOG_TAG__', tag)


def github(path):
    return json.loads(subprocess.check_output(['gh', 'api', path], text=True))


def verify_catalogue(text, tag):
    release = github('repos/tdesaules/github-actions/releases/tags/' + tag)
    if release.get('draft') or release.get('prerelease') or release.get('tag_name') != tag:
        raise ValueError('A published stable catalogue release is required')
    paths = sorted(set(re.findall(r'uses: tdesaules/github-actions/([^@\s]+)@', text)))
    for path in paths:
        record = github(f'repos/tdesaules/github-actions/contents/{path}/action.yml?ref={tag}')
        metadata = base64.b64decode(record['content']).decode()
        if not re.search(r'^  using: docker$', metadata, re.M):
            raise ValueError(f'{path}: expected a native Docker action')
        match = re.search(r'^  image: docker://(ghcr\.io/[^\s]+@sha256:[a-f0-9]{64})$', metadata, re.M)
        if not match:
            raise ValueError(f'{path}: no immutable published image')
        digest = subprocess.check_output(['oras', 'resolve', match[1]], text=True).strip()
        if digest != match[1].split('@')[1]:
            raise ValueError(f'{path}: remote digest mismatch')
        if path == 'check/test-python' and '  tests-directory:' not in metadata:
            raise ValueError('Catalogue release lacks the Python discovery input')


def activate(project, tag, directory, core='', k0s=''):
    directory = Path(directory).resolve()
    identity_file = directory / ('project.json' if project == 'system' else 'build/component.json')
    identity = json.loads(identity_file.read_text())
    if not identity.get('repository', '').endswith('/pantavisor-' + project):
        raise ValueError('Selected directory is not the requested Pantavisor project')
    if project != 'system' and identity.get('name') != project:
        raise ValueError('Producer identity differs from the requested project')
    text = render(project, tag)
    verify_catalogue(text, tag)
    references = None
    if project == 'system':
        references = {'schema': 1, 'core': core, 'k0s': k0s}
        for value in (core, k0s):
            if not PIN.fullmatch(value):
                raise ValueError('System requires published immutable Core and k0s references')
            if subprocess.check_output(['oras', 'resolve', value], text=True).strip() != value.split('@')[1]:
                raise ValueError('Component reference does not resolve to the expected digest')
    metadata = directory / '.github/pantavisor-ci.json'
    workflow = directory / '.github/workflows/main.yml'
    if workflow.exists():
        previous = json.loads(metadata.read_text()) if metadata.exists() else {}
        if hashlib.sha256(workflow.read_bytes()).hexdigest() != previous.get('workflowSha256'):
            raise ValueError('Existing main.yml has local edits or is not managed by this activator')
    # All remote checks precede source edits. Keep the original workflows intact
    # outside the active directory, including any pre-existing user changes.
    legacy = directory / '.github/legacy-workflows'
    old = [directory / '.github/workflows' / name for name in ('check.yml', 'release.yml', 'qualify.yml')]
    for path in old:
        if path.exists() and (legacy / path.name).exists():
            raise ValueError('Refusing to overwrite archived workflow: ' + path.name)
    workflow.parent.mkdir(parents=True, exist_ok=True)
    if any(path.exists() for path in old):
        legacy.mkdir(exist_ok=True)
        for path in old:
            if path.exists():
                shutil.move(path, legacy / path.name)
    atomic_write(workflow, text)
    if references:
        atomic_write(directory / 'compositions/components.json', json.dumps(references, indent=2) + '\n')
    atomic_write(metadata, json.dumps({'schema': 1, 'project': project, 'catalogueTag': tag,
                                      'workflowSha256': hashlib.sha256(text.encode()).hexdigest()}, indent=2) + '\n')
    print(f'Activated {workflow}; review and commit before pushing this consumer')


def atomic_write(path, text):
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.ci-', delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text.encode())
        stream.flush()
        os.fchmod(stream.fileno(), 0o644)
        os.fsync(stream.fileno())
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', required=True, choices=('core', 'k0s', 'system'))
    parser.add_argument('--catalogue-tag', required=True)
    parser.add_argument('--directory', type=Path)
    parser.add_argument('--core-reference', default='')
    parser.add_argument('--k0s-reference', default='')
    parser.add_argument('--render-only', type=Path, help='Write a validation fixture only; does not activate a consumer')
    args = parser.parse_args()
    if args.render_only:
        args.render_only.parent.mkdir(parents=True, exist_ok=True)
        args.render_only.write_text(render(args.project, args.catalogue_tag))
    elif args.directory:
        activate(args.project, args.catalogue_tag, args.directory, args.core_reference, args.k0s_reference)
    else:
        parser.error('--directory or --render-only is required')
